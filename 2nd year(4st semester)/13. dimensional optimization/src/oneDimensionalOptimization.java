/**
 * Класс для решения задачи многомерной оптимизации методом координатного спуска.
 *
 * Теоретическая основа (согласно методичке):
 * - Задача: поиск точки глобального минимума функции f(X) = f(x1, x2, ..., xn)
 *   с заданной точностью ε > 0: ||X* − X̃ (приближённое)|| < ε
 * - Для многомерной задачи используется метод координатного спуска:
 *   циклическая минимизация по каждой координате при фиксированных остальных
 * - Для одномерной минимизации по координате применяются:
 *   1) Метод Свенна — локализация точки минимума (поиск отрезка неопределённости)
 *   2) Метод дихотомии (половинного деления) — уточнение положения минимума
 */
public class oneDimensionalOptimization {

    // ========================================================================
    // ЦЕЛЕВАЯ ФУНКЦИЯ (Вариант 10)
    // ========================================================================

    /**
     * Многомерная целевая функция:
     * f(x1, x2, x3) = ln( 0.8*(x1 - 0.8)^4 + 0.4*(x2 - 0.4)^2 + 0.4*(x3 - 0.1)^2 + 5 )
     *
     * Теоретический минимум достигается при:
     * x1 = 0.8, x2 = 0.4, x3 = 0.1 -> f_min = ln(5) ≈ 1.6094379124
     *
     * @param x1 первая координата
     * @param x2 вторая координата
     * @param x3 третья координата
     * @return значение функции в точке (x1, x2, x3)
     */
    public static double f(double x1, double x2, double x3) {
        double term1 = 0.8 * Math.pow(x1 - 0.8, 4);
        double term2 = 0.4 * Math.pow(x2 - 0.4, 2);
        double term3 = 0.4 * Math.pow(x3 - 0.1, 2);
        return Math.log(term1 + term2 + term3 + 5);
    }

    /**
     * Одномерное сечение целевой функции по переменной с индексом idx.
     * Используется для применения одномерных методов оптимизации в рамках
     * координатного спуска.
     *
     * @param x варьируемая координата
     * @param idx индекс координаты: 0 -> x1, 1 -> x2, 2 -> x3
     * @param fixed массив фиксированных значений остальных координат
     * @return значение f при подстановке x на позицию idx
     */
    public static double f1D(double x, int idx, double[] fixed) {
        switch (idx) {
            case 0: return f(x, fixed[1], fixed[2]);  // варьируем x1
            case 1: return f(fixed[0], x, fixed[2]);  // варьируем x2
            case 2: return f(fixed[0], fixed[1], x);  // варьируем x3
            default: throw new IllegalArgumentException("Неверный индекс переменной");
        }
    }

    // ========================================================================
    // ЭТАП 1: ЛОКАЛИЗАЦИЯ ТОЧКИ МИНИМУМА (Метод Свенна)
    // ========================================================================

    /**
     * Метод Свенна для поиска начального отрезка неопределённости [a; b],
     * содержащего точку минимума одномерной функции.
     *
     * Алгоритм (согласно методичке):
     * 1. Выбрать начальную точку xo и шаг d > 0
     * 2. Вычислить f(xo-d), f(xo), f(xo+d)
     * 3. Проверить условия унимодальности:
     *    - если f(xo-d) < f(xo) > f(xo+d) -> функция не унимодальна
     *    - если f(xo-d) > f(xo) < f(xo+d) -> отрезок найден: [xo-d; xo+d]
     * 4. Если функция монотонна, строить последовательность с удваивающимся шагом:
     *    xk = xk-1 ± 2^(k-1)·d (знак зависит от направления убывания)
     * 5. Остановиться, когда найдётся тройка точек, удовлетворяющая условию
     *    унимодальности: f(xk-1) > f(xk) < f(xk+1)
     * 6. Вернуть отрезок [a; b] = [xk-1; xk+1] (или обратный порядок при h < 0)
     *
     * @param xo начальная точка поиска
     * @param d начальный шаг
     * @param idx индекс варьируемой координаты
     * @param fixed фиксированные значения остальных координат
     * @return массив {a, b} — границы отрезка неопределённости
     */
    private static double[] swenn1D(double xo, double d, int idx, double[] fixed) {

        // Вычисление значений функции в трёх соседних точках (шаг 2 алгоритма)
        double fPrev = f1D(xo - d, idx, fixed);
        double fCurr = f1D(xo, idx, fixed);
        double fNext = f1D(xo + d, idx, fixed);

        // Проверка условия неунимодальности (шаг 3)
        if (fPrev < fCurr && fCurr > fNext) {
            throw new IllegalStateException("Функция не унимодальна вдоль выбранного направления!");
        }

        // Отрезок найден на первой итерации (шаг 4)
        if (fPrev > fCurr && fCurr < fNext) {
            return new double[]{xo - d, xo + d};
        }

        // Определение направления поиска (шаги 5–6)
        double h;
        if (fPrev > fCurr && fCurr > fNext) {
            h = d;   // функция убывает -> минимум правее -> двигаемся вправо
        } else if (fPrev < fCurr && fCurr < fNext) {
            h = -d;  // функция возрастает -> минимум левее -> двигаемся влево
        } else {
            throw new IllegalStateException("Невозможно определить направление поиска");
        }

        // Инициализация последовательности с удваивающимся шагом
        double xPrev = xo - h;
        double xCurr = xo;
        double xNext = xo + h;
        int iter = 0;

        // Построение последовательности до выполнения условия унимодальности
        while (true) {
            double fp = f1D(xPrev, idx, fixed);
            double fc = f1D(xCurr, idx, fixed);
            double fn = f1D(xNext, idx, fixed);

            // Условие остановки: найден локальный минимум между xPrev и xNext
            if (fp > fc && fc < fn) break;

            // Удвоение шага и сдвиг тройки точек (формула xk = xk-1 ± 2^(k-1)·d)
            h *= 2;
            xPrev = xCurr;
            xCurr = xNext;
            xNext = xCurr + h;

            // Защита от зацикливания и переполнения
            if (++iter > 1000 || Math.abs(h) > 1e10) {
                throw new RuntimeException("Не удалось найти интервал унимодальности");
            }
        }

        // Формирование отрезка неопределённости [a; b]
        return h > 0 ? new double[]{xPrev, xNext} : new double[]{xNext, xPrev};
    }

    // ========================================================================
    // ЭТАП 2: УТОЧНЕНИЕ ПОЛОЖЕНИЯ МИНИМУМА (Метод дихотомии)
    // ========================================================================

    /**
     * Метод половинного деления (дихотомии) для уточнения точки минимума
     * на отрезке неопределённости [a; b].
     *
     * Алгоритм (согласно методичке):
     * 1. Задать точность ε > 0, положить k = 0, x0 = a, x4 = b
     * 2. Вычислить внутренние точки:
     *    x1 = (3·x0 + x4)/4,  x2 = (x0 + x4)/2,  x3 = (x0 + 3·x4)/4
     * 3. Вычислить f(x1), f(x2), f(x3)
     * 4. Сузить отрезок в зависимости от соотношения значений:
     *    - если f(x1) > f(x2) < f(x3) -> новый отрезок [x1; x3]
     *    - если f(x1) > f(x2) > f(x3) -> новый отрезок [x2; x4]
     *    - если f(x1) < f(x2) < f(x3) -> новый отрезок [x0; x2]
     * 5. Повторять, пока длина отрезка bk − ak ≥ 2ε
     * 6. Вернуть приближение x̃ = (ak + bk)/2
     *
     * Свойство: длина отрезка сокращается вдвое за итерацию.
     *
     * @param ab массив {a, b} — начальный отрезок неопределённости
     * @param eps требуемая точность
     * @param idx индекс варьируемой координаты
     * @param fixed фиксированные значения остальных координат
     * @return приближённое значение точки минимума
     */
    private static double halfDivision1D(double[] ab, double eps, int idx, double[] fixed) {
        double a = ab[0];
        double b = ab[1];

        // Итерационный процесс вложенных отрезков
        while (b - a >= 2 * eps) {

            // Вычисление точек деления (шаг 2 алгоритма)
            double x1 = (3 * a + b) / 4.0;
            double x2 = (a + b) / 2.0;   // средняя точка
            double x3 = (a + 3 * b) / 4.0;

            // Вычисление значений функции (шаг 3)
            double f1 = f1D(x1, idx, fixed);
            double f2 = f1D(x2, idx, fixed);
            double f3 = f1D(x3, idx, fixed);

            // Сужение отрезка неопределённости (шаг 4)
            if (f1 > f2 && f2 < f3) {

                // Минимум внутри [x1; x3]
                a = x1; b = x3;
            } else if (f1 > f2 && f2 > f3) {

                // Функция убывает -> минимум правее x2
                a = x2;
            } else if (f1 < f2 && f2 < f3) {

                // Функция возрастает -> минимум левее x2
                b = x2;
            } else {

                // Запасной вариант для численной устойчивости
                b = x3;
            }
        }

        // Возврат середины финального отрезка (шаг 6)
        return (a + b) / 2.0;
    }

    // ========================================================================
    // МНОГОМЕРНАЯ ОПТИМИЗАЦИЯ: МЕТОД КООРДИНАТНОГО СПУСКА
    // ========================================================================

    /**
     * Метод координатного спуска для минимизации многомерной функции.
     *
     * Принцип работы:
     * - На каждой итерации последовательно минимизируем функцию по одной
     *   координате при фиксированных остальных (цикл x1 -> x2 -> x3)
     * - Для одномерной минимизации по координате используются:
     *   • метод Свенна — для локализации отрезка неопределённости
     *   • метод дихотомии — для уточнения точки минимума на отрезке
     *
     * Критерий остановки:
     * - Достигнуто максимальное число итераций ИЛИ
     * - Изменение значения функции |f_prev − f_curr| < ε
     *
     * @param x0 начальное приближение точки минимума
     * @param eps точность по значению функции
     * @param maxIter максимальное число итераций
     * @return массив координат найденной точки минимума
     */
    public static double[] coordinateDescent(double[] x0, double eps, int maxIter) {
        double[] x = x0.clone();    // текущая точка (копии для сохранения истории)
        double prevF = f(x[0], x[1], x[2]);

        for (int iter = 0; iter < maxIter; iter++) {

            // --- Оптимизация по координате x1 (индекс 0) ---
            // Локализация отрезка неопределённости методом Свенна
            double[] interval = swenn1D(x[0], 0.1, 0, new double[]{x[0], x[1], x[2]});

            // Уточнение точки минимума на отрезке методом дихотомии
            x[0] = halfDivision1D(interval, eps, 0, new double[]{x[0], x[1], x[2]});

            // --- Оптимизация по координате x2 (индекс 1) ---
            // Важно: используем уже обновлённое значение x[0]
            interval = swenn1D(x[1], 0.1, 1, new double[]{x[0], x[1], x[2]});

            x[1] = halfDivision1D(interval, eps, 1, new double[]{x[0], x[1], x[2]});

            // --- Оптимизация по координате x3 (индекс 2) ---
            // Используются обновлённые x[0] и x[1]
            interval = swenn1D(x[2], 0.1, 2, new double[]{x[0], x[1], x[2]});
            x[2] = halfDivision1D(interval, eps, 2, new double[]{x[0], x[1], x[2]});

            // Проверка критерия сходимости
            double currF = f(x[0], x[1], x[2]);
            double diff = Math.abs(prevF - currF);

            // Остановка при достижении заданной точности
            if (diff < eps) {
                System.out.printf("Сходимость достигнута на итерации %d%n", iter + 1);
                break;
            }
            prevF = currF;
        }

        return x;
    }

    public static void main(String[] args) {
        try {

            // Начальная точка (аналог xo = 19.7 из VBA-примера для всех координат)
            double[] x0 = {19.7, 19.7, 19.7};
            double eps = 0.0001;      // требуемая точность
            int maxIter = 100;        // ограничение на число итераций

            System.out.println("=== Поиск минимума функции (Вариант 10) ===");
            System.out.println("Метод: координатный спуск + Свенн + дихотомия");
            System.out.printf("Начальная точка: [%.1f, %.1f, %.1f]%n", x0[0], x0[1], x0[2]);
            System.out.println("Точность: eps = " + eps);
            System.out.println();

            // Запуск оптимизации
            double[] result = coordinateDescent(x0, eps, maxIter);

            // Вывод результатов
            System.out.println("\n=== Результат ===");
            System.out.printf("Точка минимума: [%.6f, %.6f, %.6f]%n",
                    result[0], result[1], result[2]);

            System.out.printf("Значение функции: f = %.10f%n",
                    f(result[0], result[1], result[2]));

            System.out.printf("Теоретический минимум: [0.8, 0.4, 0.1], f = %.10f%n",
                    Math.log(5));

        } catch (Exception e) {

            System.err.println("Ошибка выполнения: " + e.getMessage());

            e.printStackTrace();
        }
    }
}