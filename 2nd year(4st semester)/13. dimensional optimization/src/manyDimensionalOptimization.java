/**
 * Класс реализации градиентного метода (метода наискорейшего спуска)
 * для многомерной оптимизации без ограничений.
 *
 * Теоретическая основа (согласно методичке, стр. 6-10):
 *
 * 1. Постановка задачи:
 *    - Дана гладкая функция f(X) = f(x1, x2, ..., xn), имеющая внутри области
 *      определения точку глобального минимума X*
 *    - Требуется найти приближение X~ такое, что ||X* - X~|| < eps
 *
 * 2. Градиентный метод (метод наискорейшего спуска):
 *    - Вектор градиента grad f(X) = {df/dx1, df/dx2, ..., df/dxn} указывает
 *      направление наискорейшего возрастания функции
 *    - Вектор антиградиента -grad f(X) указывает направление наискорейшего убывания
 *
 * 3. Итерационный процесс (алгоритм из методички, стр. 6-7):
 *    а) Задать точность eps > 0, начальную точку X^0, k = 0
 *    б) Вычислить градиент grad f(X^k)
 *    в) Найти шаг alpha >= 0, минимизирующий функцию одного аргумента:
 *       h(alpha, X^k) = f(X^k - alpha * grad f(X^k))  [линейный поиск]
 *    г) Обновить точку: X^(k+1) = X^k - alpha * grad f(X^k)
 *    д) Проверить критерии остановки:
 *       - ||grad f(X^(k+1))|| < eps (градиент мал -> стационарная точка)
 *       - ||X^(k+1) - X^k|| < eps (аргумент почти не меняется -> сходимость)
 *    е) Если критерий не выполнен: k <- k+1, перейти к шагу (б)
 *
 * 4. Для одномерной минимизации h(alpha) используются:
 *    - Метод Свенна: локализация отрезка неопределённости [a; b] (стр. 1-2)
 *    - Метод дихотомии: уточнение положения минимума на отрезке (стр. 2-3)
 */
public class manyDimensionalOptimization {

    // ========================================================================
    // ВЕКТОРНЫЕ ОПЕРАЦИИ (вспомогательные методы для R^3)
    // ========================================================================

    /**
     * Сложение векторов: c = a + b (покомпонентно)
     * Используется для вычисления X^(k+1) = X^k - alpha * grad f(X^k)
     */
    public static double[] plus(double[] a, double[] b) {
        double[] c = new double[3];
        for (int n = 0; n < 3; n++) {
            c[n] = a[n] + b[n];
        }
        return c;
    }

    /**
     * Вычитание векторов: c = a - b (покомпонентно)
     * Ключевая операция для шага градиентного спуска:
     * X^(k+1) = X^k - alpha * grad f(X^k)
     */
    public static double[] minus(double[] a, double[] b) {
        double[] c = new double[3];
        for (int n = 0; n < 3; n++) {
            c[n] = a[n] - b[n];
        }
        return c;
    }

    /**
     * Умножение вектора на скаляр: c = a * t (покомпонентно)
     * Используется для вычисления направления спуска: alpha * grad f(X^k)
     */
    public static double[] mult(double[] a, double t) {
        double[] c = new double[3];
        for (int n = 0; n < 3; n++) {
            c[n] = a[n] * t;
        }
        return c;
    }

    /**
     * Скалярное произведение: a*b = сумма a[i]*b[i]
     * Используется для вычисления евклидовой нормы вектора
     */
    public static double scalProd(double[] a, double[] b) {
        double scp = 0;
        for (int n = 0; n < 3; n++) {
            scp += a[n] * b[n];
        }
        return scp;
    }

    /**
     * Евклидова норма (длина) вектора: |a| = sqrt(a*a)
     *
     * Критерии остановки (согласно методичке, стр. 7):
     * - ||grad f(X^(k+1))|| < eps - градиент мал, найдена стационарная точка
     * - ||X^(k+1) - X^k|| < eps - изменение аргумента мало, достигнута сходимость
     */
    public static double length(double[] a) {
        return Math.sqrt(scalProd(a, a));
    }

    // ========================================================================
    // ЦЕЛЕВАЯ ФУНКЦИЯ И ГРАДИЕНТ (Вариант 10)
    // ========================================================================

    /**
     * Целевая функция (Вариант 10 из задания, стр. 11):
     * f(x1, x2, x3) = ln( 0.8*(x1 - 0.8)^4 + 0.4*(x2 - 0.4)^2 + 0.4*(x3 - 0.1)^2 + 5 )
     *
     * Свойства функции:
     * - Область определения: всё R^3 (выражение под логарифмом всегда >= 5 > 0)
     * - Функция гладкая (бесконечно дифференцируемая)
     * - Глобальный минимум достигается при:
     *   x1 = 0.8, x2 = 0.4, x3 = 0.1 -> f_min = ln(5) ~ 1.6094379124
     *
     * @param x массив координат {x1, x2, x3}
     * @return значение функции f(x)
     */
    public static double f(double[] x) {
        double term = 0.8 * Math.pow(x[0] - 0.8, 4)
                + 0.4 * Math.pow(x[1] - 0.4, 2)
                + 0.4 * Math.pow(x[2] - 0.1, 2)
                + 5;
        return Math.log(term);
    }

    /**
     * Градиент целевой функции: grad f = [df/dx1, df/dx2, df/dx3]
     *
     * Вычисление через цепное правило: d/dx ln(u) = u' / u
     *
     * Обозначим D = 0.8*(x1-0.8)^4 + 0.4*(x2-0.4)^2 + 0.4*(x3-0.1)^2 + 5
     *
     * Частные производные (согласно методичке, стр. 7):
     * df/dx1 = [3.2*(x1 - 0.8)^3] / D
     * df/dx2 = [0.8*(x2 - 0.4)] / D
     * df/dx3 = [0.8*(x3 - 0.1)] / D
     *
     * @param x массив координат {x1, x2, x3}
     * @return вектор градиента {df/dx1, df/dx2, df/dx3}
     */
    public static double[] gradF(double[] x) {
        double[] grad = new double[3];

        // Общий знаменатель D (одинаков для всех компонент)
        double D = 0.8 * Math.pow(x[0] - 0.8, 4)
                + 0.4 * Math.pow(x[1] - 0.4, 2)
                + 0.4 * Math.pow(x[2] - 0.1, 2)
                + 5;

        // Компоненты градиента (формулы из методички, стр. 7)
        grad[0] = (3.2 * Math.pow(x[0] - 0.8, 3)) / D;  // df/dx1
        grad[1] = (0.8 * (x[1] - 0.4)) / D;             // df/dx2
        grad[2] = (0.8 * (x[2] - 0.1)) / D;             // df/dx3

        return grad;
    }

    // ========================================================================
    // ЭТАП 1: ЛОКАЛИЗАЦИЯ (Метод Свенна для линейного поиска)
    // ========================================================================

    /**
     * Метод Свенна для поиска отрезка неопределённости [a; b],
     * содержащего точку минимума одномерной функции phi(alpha) = f(X - alpha * grad f(X)).
     *
     * Алгоритм (согласно методичке, стр. 1-2):
     *
     * 1. Выбрать начальную точку t = 0 и шаг d > 0
     * 2. Вычислить значения функции в трёх точках:
     *    xL = X - (t-d)*grad f(X),  xC = X - t*grad f(X),  xH = X - (t+d)*grad f(X)
     * 3. Проверить условия унимодальности:
     *    - если f(xL) < f(xC) > f(xH) -> функция не унимодальна (стоп)
     *    - если f(xL) > f(xC) < f(xH) -> отрезок найден: [t-d; t+d]
     * 4. Если функция монотонна, строить последовательность с удваивающимся шагом:
     *    tk = tk-1 +- 2^(k-1)*d (знак зависит от направления убывания)
     * 5. Остановиться, когда найдётся тройка точек, удовлетворяющая условию:
     *    f(xk-1) > f(xk) < f(xk+1)
     * 6. Вернуть отрезок [a; b] = [tk-1; tk+1] (или обратный порядок при h < 0)
     *
     * @param x текущая точка многомерной оптимизации X^k
     * @param d начальный шаг для поиска
     * @return массив {a, b} - границы отрезка неопределённости для параметра alpha
     */
    public static double[] swenn(double[] x, double d) {
        double t = 0; // Начальное значение параметра alpha (шаг 1 алгоритма)

        // Вычисление точек вдоль направления антиградиента (шаг 2)
        // Формула: x(alpha) = X - alpha * grad f(X)
        double[] xL = minus(x, mult(gradF(x), t - d)); // alpha = -d
        double[] xC = minus(x, mult(gradF(x), t));     // alpha = 0
        double[] xH = minus(x, mult(gradF(x), t + d)); // alpha = +d

        double a = 0, b = 0;

        // Проверка условия неунимодальности (шаг 3, первое условие)
        if (f(xL) < f(xC) && f(xC) > f(xH)) {
            System.out.println("Функция не унимодальна на начальном интервале!");
            a = 0; b = 0;
        }
        // Отрезок найден на первой итерации (шаг 4)
        else if (f(xL) > f(xC) && f(xC) < f(xH)) {
            a = t - d;
            b = t + d;
        }
        // Функция монотонна - расширяем интервал (шаги 5-6)
        else {
            // Определение направления поиска
            double h;
            if (f(xL) > f(xC) && f(xC) > f(xH)) {
                h = d;   // функция убывает при росте alpha -> двигаемся вправо
            } else {
                h = -d;  // функция убывает при уменьшении alpha -> двигаемся влево
            }

            // Инициализация последовательности с удваивающимся шагом
            double tPrev = t - h;
            double[] xPrev = minus(x, mult(gradF(x), tPrev));
            double tCurr = t;
            double[] xCurr = minus(x, mult(gradF(x), tCurr));
            double tNext = t + h;
            double[] xNext = minus(x, mult(gradF(x), tNext));

            // Построение последовательности до выполнения условия унимодальности
            while (!((f(xPrev) > f(xCurr)) && (f(xCurr) < f(xNext)))) {
                h *= 2;  // Удвоение шага: tk = tk-1 +- 2^(k-1)*d
                tPrev = tCurr;  xPrev = xCurr;
                tCurr = tNext;  xCurr = xNext;
                tNext = t + h;
                xNext = minus(x, mult(gradF(x), tNext));
            }

            // Формирование отрезка неопределённости [a; b]
            if (h > 0) {
                a = tPrev; b = tNext;
            } else {
                a = tNext; b = tPrev;
            }
        }

        return new double[]{a, b};
    }

    // ========================================================================
    // ЭТАП 2: УТОЧНЕНИЕ (Метод дихотомии для линейного поиска)
    // ========================================================================

    /**
     * Метод половинного деления (дихотомии) для уточнения точки минимума
     * одномерной функции phi(alpha) = f(X - alpha * grad f(X)) на отрезке [a; b].
     *
     * Алгоритм (согласно методичке, стр. 2-3):
     *
     * 1. Задать точность eps > 0, положить k = 0, t0 = a, t4 = b
     * 2. Вычислить внутренние точки:
     *    t1 = (3*t0 + t4)/4,  t2 = (t0 + t4)/2,  t3 = (t0 + 3*t4)/4
     * 3. Вычислить phi(t1), phi(t2), phi(t3) через f(X - ti * grad f(X))
     * 4. Сузить отрезок в зависимости от соотношения значений:
     *    - если phi(t1) > phi(t2) < phi(t3) -> новый отрезок [t1; t3]
     *    - если phi(t1) > phi(t2) > phi(t3) -> новый отрезок [t2; t4]
     *    - если phi(t1) < phi(t2) < phi(t3) -> новый отрезок [t0; t2]
     * 5. Повторять, пока длина отрезка tk4 - tk0 >= 2*eps
     * 6. Вернуть приближение alpha~ = (tk0 + tk4)/2
     *
     * Свойство: длина отрезка сокращается вдвое за итерацию.
     *
     * @param x   текущая точка многомерной оптимизации X^k
     * @param ab  начальный отрезок неопределённости {a, b} от метода Свенна
     * @param eps требуемая точность локализации минимума
     * @return приближённое значение оптимального шага alpha
     */
    public static double halfDivision(double[] x, double[] ab, double eps) {
        int k = 0;              // Счётчик итераций
        double t0 = ab[0];      // Левая граница: x0 = X - t0 * grad f(X)
        double[] x0 = minus(x, mult(gradF(x), t0));
        double t4 = ab[1];      // Правая граница: x4 = X - t4 * grad f(X)
        double[] x4 = minus(x, mult(gradF(x), t4));

        // Итерационный процесс вложенных отрезков
        do {

            // Вычисление точек деления (шаг 2 алгоритма)
            double t1 = (3 * t0 + t4) / 4.0;
            double[] x1 = minus(x, mult(gradF(x), t1));

            double t2 = (2 * t0 + 2 * t4) / 4.0; // = (t0 + t4) / 2
            double[] x2 = minus(x, mult(gradF(x), t2));

            double t3 = (t0 + 3 * t4) / 4.0;
            double[] x3 = minus(x, mult(gradF(x), t3));

            // Сужение отрезка неопределённости (шаг 4)
            if (f(x1) > f(x2) && f(x2) < f(x3)) {

                // Минимум внутри [t1; t3]
                t0 = t1; t4 = t3;
            } else if (f(x1) > f(x2) && f(x2) > f(x3)) {

                // Функция убывает -> минимум правее t2
                t0 = t2;
            } else if (f(x1) < f(x2) && f(x2) < f(x3)) {

                // Функция возрастает -> минимум левее t2
                t4 = t2;
            }
            k++;
        } while ((t4 - t0) >= 2 * eps); // Критерий остановки: длина отрезка

        // Возврат середины финального отрезка (шаг 6)
        return (t0 + t4) / 2.0;
    }

    // ========================================================================
    // ВСПОМОГАТЕЛЬНЫЙ МЕТОД ВЫВОДА
    // ========================================================================

    /**
     * Форматированный вывод информации об итерации.
     * Показывает: номер итерации, координаты точки, значение функции, норму градиента.
     */
    private static void printIteration(int k, double[] x, double fx) {
        System.out.printf("k=%2d | x=[%7.4f, %7.4f, %7.4f] | f(x)=%9.6f | |grad f|=%9.6f%n",
                k, x[0], x[1], x[2], fx, length(gradF(x)));
    }

    // ========================================================================
    // ГЛАВНАЯ ПРОГРАММА: ГРАДИЕНТНЫЙ СПУСК
    // ========================================================================

    /**
     * Основной алгоритм оптимизации методом наискорейшего спуска.
     *
     * Схема работы (согласно методичке, стр. 6-7):
     *
     * Инициализация:
     *   - Задать точность eps > 0
     *   - Выбрать начальную точку X^0 произвольным образом
     *   - Положить k = 0
     *
     * Цикл по итерациям:
     *   1. Вычислить вектор градиента grad f(X^k)
     *   2. Найти оптимальный шаг alpha >= 0, минимизирующий:
     *      h(alpha, X^k) = f(X^k - alpha * grad f(X^k))
     *      с помощью методов Свенна и дихотомии
     *   3. Обновить точку: X^(k+1) = X^k - alpha * grad f(X^k)
     *   4. Проверить критерии остановки:
     *      - ||grad f(X^(k+1))|| < eps (градиент мал -> стационарная точка)
     *      - ||X^(k+1) - X^k|| < eps (аргумент почти не меняется -> сходимость)
     *   5. Если критерий не выполнен: k <- k+1, перейти к шагу 1
     *
     * Выход: приближённое значение точки минимума X~ = X^(k+1)
     */
    public static void main(String[] args) {

        // Начальное приближение (из оригинального кода VBA, стр. 10)
        // Намеренно взято далеко от минимума для демонстрации сходимости
        double[] x = {5.317, 4.196, 3.174};

        // Параметры алгоритма
        final double EPS_GRAD = 0.0001;      // Точность по норме градиента (критерий 1)
        final double EPS_STEP = 0.0001;      // Точность по изменению аргумента (критерий 2)
        final double SWENN_D = 0.01;         // Начальный шаг для метода Свенна
        final double LINE_EPS = 0.0001;      // Точность линейного поиска (дихотомия)

        int k = 0; // Счётчик итераций

        // Заголовок вывода
        System.out.println("=== ГРАДИЕНТНЫЙ СПУСК С АДАПТИВНЫМ ШАГОМ ===");
        System.out.println("Целевая функция: f(x) = ln(0.8*(x1-0.8)^4 + 0.4*(x2-0.4)^2 + 0.4*(x3-0.1)^2 + 5)");
        System.out.println("Точный минимум:  x* = [0.8, 0.4, 0.1]");
        System.out.println("f_min = ln(5) = " + Math.log(5));
        System.out.println("================================================\n");

        // Вывод начальной точки
        printIteration(k, x, f(x));

        double[] xNew = x.clone(); // Текущая точка
        double[] xOld;             // Предыдущая точка (для проверки сходимости)

        // ==================== ОСНОВНОЙ ЦИКЛ ОПТИМИЗАЦИИ ====================
        do {
            xOld = xNew.clone(); // Сохранение точки перед шагом

            // --- ЭТАП 1: Локализация отрезка неопределённости (метод Свенна) ---
            // Поиск интервала [a; b] для функции h(alpha) = f(X^k - alpha * grad f(X^k))
            double[] interval = swenn(xOld, SWENN_D);

            // --- ЭТАП 2: Уточнение оптимального шага (метод дихотомии) ---
            // Сужение интервала до длины < 2*LINE_EPS
            double alpha = halfDivision(xOld, interval, LINE_EPS);

            // --- ЭТАП 3: Шаг градиентного спуска ---
            // Формула обновления: X^(k+1) = X^k - alpha * grad f(X^k) (методичка, стр. 7)
            xNew = minus(xOld, mult(gradF(xOld), alpha));

            k++;
            printIteration(k, xNew, f(xNew)); // Вывод прогресса

            // Защита от бесконечного цикла
            if (k > 1000) {
                System.out.println("Предупреждение: Превышено максимальное число итераций (1000). Остановка.");
                break;
            }

        } while (!(length(gradF(xNew)) < EPS_GRAD || length(minus(xNew, xOld)) < EPS_STEP));
        // Цикл продолжается, пока не выполнится ХОТЯ БЫ ОДИН из критериев остановки

        System.out.println("\n=== РЕЗУЛЬТАТ ОПТИМИЗАЦИИ ===");
        System.out.printf("Найдено решение: x = [%.8f, %.8f, %.8f]%n", xNew[0], xNew[1], xNew[2]);
        System.out.printf("Значение функции:  f(x) = %.8f%n", f(xNew));
        System.out.printf("Норма градиента:   |grad f| = %.2e%n", length(gradF(xNew)));
        System.out.printf("Число итераций:    k = %d%n", k);

        // Сравнение с известным точным решением (для верификации)
        double[] exact = {0.8, 0.4, 0.1};
        System.out.printf("\nТочное решение:    x* = [%.8f, %.8f, %.8f]%n", exact[0], exact[1], exact[2]);
        System.out.printf("Абсолютная погрешность: dx = [%.2e, %.2e, %.2e]%n",
                Math.abs(xNew[0]-exact[0]),
                Math.abs(xNew[1]-exact[1]),
                Math.abs(xNew[2]-exact[2]));

        // Интерпретация результата
        if (length(gradF(xNew)) < EPS_GRAD) {
            System.out.println("\nКритерий остановки: норма градиента меньше порога (стационарная точка).");
        } else {
            System.out.println("\nКритерий остановки: изменение аргумента меньше порога (сходимость).");
        }
    }
}