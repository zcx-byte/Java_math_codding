// ============================================================================
// Файл: SimpsonsMethod.java
// Интеграл (б): integral[0.4; 1.2] log_2(x^2 + 2) / (x + 1) dx
// Метод: Симпсона (параболических трапеций)
// Точность: epsilon = 0.001
// ============================================================================

public class SimpsonsMethod {

    // =========================================================================
    // ВСПОМОГАТЕЛЬНАЯ ФУНКЦИЯ
    // =========================================================================

    /**
     * Подынтегральная функция для интеграла (б).
     *
     * f(x) = log_2(x^2 + 2) / (x + 1)
     *
     * Примечание: log_2(x) = ln(x) / ln(2) - переход к основанию 2
     *
     * @param x - аргумент функции
     * @return значение f(x) в точке x
     */
    public static double f(double x) {
        double numerator = Math.log(x * x + 2) / Math.log(2); // log_2(x^2 + 2)
        double denominator = x + 1;
        return numerator / denominator;
    }

    // =========================================================================
    // МЕТОД СИМПСОНА
    // =========================================================================

    /**
     * Вычисление integral[a; b] f(x)dx методом Симпсона с контролем точности.
     *
     * МЕТОД СИМПСОНА (параболических трапеций):
     * - Число частичных отрезков должно быть чётным: n = 2*m
     * - Отрезок [a; b] разбивается на n равных частей:
     *   x_0 = a, x_1, x_2, ..., x_n = b
     * - Шаг: h = (b - a) / n (постоянная величина)
     *
     * На каждой паре отрезков [x_{2k-2}; x_{2k}] кривая y = f(x) заменяется
     * параболой, проходящей через три точки.
     *
     * ОБЩАЯ ФОРМУЛА:
     * integral[a; b] f(x)dx ~ h/3 * (f(x_0) + f(x_n) + 
     *                                4*sum f(x_{2k-1}) + 
     *                                2*sum f(x_{2k})),
     * где первая сумма по k = 1..m (нечётные узлы),
     *       вторая сумма по k = 1..m-1 (чётные узлы)
     *
     * ПОГРЕШНОСТЬ (оценка сверху):
     * max |f^(4)(x)| * (b - a)^5
     * x in [a; b]
     * R <= -----------------------
     *              180*n^4
     *
     * @param a - нижний предел интегрирования
     * @param b - верхний предел интегрирования
     * @param epsilon - требуемая точность (epsilon = 0.001)
     * @return приближённое значение интеграла
     */
    public static double calculateIntegral(double a, double b, double epsilon) {

        int n = 4;                  // начальное число интервалов (должно быть чётным!)
        double prevResult = 0;      // результат при предыдущем n
        double currentResult;       // результат при текущем n
        int m;                      // число пар отрезков: m = n / 2
        double h;                   // шаг интегрирования

        System.out.println("Вычисление integral[" + a + "; " + b + "] f(x)dx методом Симпсона:");
        System.out.println("Точность: epsilon = " + epsilon);
        System.out.println();

        // Цикл удвоения n до достижения |I_n - I_{n/2}| < epsilon
        do {

            m = n / 2;              // число пар отрезков
            h = (b - a) / n;        // шаг: h = (b - a) / n

            // === ФОРМУЛА СИМПСОНА ===
            // I ~ (интеграл приблизительно равен)
            // I ~ h/3 * [f(x_0) + f(x_n) + 4*sum_odd + 2*sum_even]

            // Сумма по нечётным узлам (коэффициент 4):
            // x_{2k-1} = a + (2*k - 1)*h, k = 1, 2, ..., m
            double sumOdd = 0;
            for (int k = 1; k <= m; k++) {
                double xk = a + (2 * k - 1) * h;    // нечётный узел: x_{2k-1}
                sumOdd += f(xk);
            }

            // Сумма по чётным узлам (коэффициент 2):
            // x_{2k} = a + 2*k*h, k = 1, 2, ..., m-1
            double sumEven = 0;
            for (int k = 1; k <= m - 1; k++) {
                double xk = a + 2 * k * h;       // чётный узел: x_{2k}
                sumEven += f(xk);
            }

            // Применяем формулу Симпсона:
            currentResult = (h / 3) * (f(a) + f(b) + 4 * sumOdd + 2 * sumEven);

            System.out.println("  n = " + n + ", m = " + m + ", h = " + String.format("%.6f", h) +
                    ", I ~ " + String.format("%.6f", currentResult));

            n *= 2; // удваиваем число интервалов: n = 2*n (остаётся чётным)

        } while (Math.abs(currentResult - prevResult) >= epsilon && n < 10000);
        // Условие остановки: |I_n - I_{n/2}| < epsilon

        System.out.println();
        System.out.println("  Достигнута точность: epsilon = " + epsilon);
        return currentResult;
    }

    // =========================================================================
    // ГЛАВНЫЙ МЕТОД
    // =========================================================================

    /**
     * Точка входа в программу.
     * Вычисляет интеграл (б) варианта №10.
     */
    public static void main(String[] args) {
        double epsilon = 0.001; // требуемая точность

        // Пределы интегрирования для варианта №10 (б)
        double a = 0.4;
        double b = 1.2;

        // Вычисление интеграла
        double result = calculateIntegral(a, b, epsilon);

        // Вывод результата
        System.out.println();
        System.out.println("========================================");
        System.out.println("ОТВЕТ для интеграла (б):");
        System.out.println("integral[0.4; 1.2] log_2(x^2 + 2) / (x + 1) dx = " + result);
        System.out.println("========================================");
    }
}