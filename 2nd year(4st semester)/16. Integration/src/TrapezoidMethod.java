// ============================================================================
// Файл: TrapezoidMethod.java
// Интеграл (а): integral[0.8; 1.8] dx / sqrt(3*x^2 + 1)
// Метод: трапеций
// Точность: epsilon = 0.001
// ============================================================================

public class TrapezoidMethod {

    // =========================================================================
    // ВСПОМОГАТЕЛЬНАЯ ФУНКЦИЯ
    // =========================================================================

    /**
     * Подынтегральная функция для интеграла (а).
     *
     * f(x) = 1 / sqrt(3*x^2 + 1)
     *
     * @param x - аргумент функции
     * @return значение f(x) в точке x
     */
    public static double f(double x) {
        return 1.0 / Math.sqrt(3 * x * x + 1);
    }

    // =========================================================================
    // МЕТОД ТРАПЕЦИЙ
    // =========================================================================

    /**
     * Вычисление integral[a; b] f(x)dx методом трапеций с контролем точности.
     *
     * МЕТОД ТРАПЕЦИЙ:
     * - Отрезок [a; b] разбивается на n равных частей:
     *   x_0 = a, x_1, x_2, ..., x_n = b
     * - Шаг: h = (b - a) / n (постоянная величина)
     * - Узлы: x_k = a + k*h, где k = 0, 1, 2, ..., n
     *
     * На каждом отрезке [x_{k-1}; x_k] кривая y = f(x) заменяется прямой.
     * Площадь трапеции: (f(x_{k-1}) + f(x_k)) / 2 * h
     *
     * ОБЩАЯ ФОРМУЛА:
     * integral[a; b] f(x)dx ~ h/2 * (f(x_0) + f(x_n) + 2*sum f(x_k)),
     * где sum - сумма по k = 1..n-1
     *
     * ПОГРЕШНОСТЬ (оценка сверху):
     * max |f''(x)| * (b - a)^3
     * x in [a; b]
     * R <= -----------------------
     *              12*n^2
     *
     * @param a - нижний предел интегрирования
     * @param b - верхний предел интегрирования
     * @param epsilon - требуемая точность (epsilon = 0.001)
     * @return приближённое значение интеграла
     */
    public static double calculateIntegral(double a, double b, double epsilon) {

        int n = 10;                      // начальное число интервалов разбиения
        double prevResult = 0;          // результат при предыдущем n
        double currentResult;           // результат при текущем n

        System.out.println("Вычисление integral[" + a + "; " + b + "] f(x)dx методом трапеций:");
        System.out.println("Точность: epsilon = " + epsilon);
        System.out.println();

        // Цикл удвоения n до достижения |I_n - I_{n/2}| < epsilon
        do {
            double h = (b - a) / n; // шаг: h = (b - a) / n

            // === ФОРМУЛА ТРАПЕЦИЙ ===
            // I ~ (интеграл приблизительно равен)
            // I ~ h/2 * [f(x_0) + f(x_n) + 2*(f(x_1) + f(x_2) + ... + f(x_{n-1}))]

            // Крайние точки с коэффициентом 1/2:
            currentResult = (f(a) + f(b)) / 2;

            // Внутренние точки с коэффициентом 1:
            // x_k = a + k*h, k = 1, 2, ..., n-1
            for (int k = 1; k < n; k++) {
                double xk = a + k * h; // текущий узел: x_k
                currentResult += f(xk);
            }

            // Умножаем сумму на h:
            currentResult *= h;

            System.out.println("  n = " + n + ", h = " + String.format("%.6f", h) +
                    ", I ~ " + String.format("%.6f", currentResult));

            n *= 2; // удваиваем число интервалов: n = 2*n

        } while (Math.abs(currentResult - prevResult) >= epsilon && n < 10000);
        // Условие остановки: |I_n - I_{n/2}| < epsilon

        System.out.println();
        System.out.println("  Достигнута точность: epsilon = " + epsilon);
        return currentResult;
    }

    // =========================================================================
    // ГЛАВНЫЙ МЕТОД
    // =========================================================================

    /**
     * Точка входа в программу.
     * Вычисляет интеграл (а) варианта №10.
     */
    public static void main(String[] args) {
        double epsilon = 0.001; // требуемая точность

        // Пределы интегрирования для варианта №10 (а)
        double a = 0.8;
        double b = 1.8;

        // Вычисление интеграла
        double result = calculateIntegral(a, b, epsilon);

        // Вывод результата
        System.out.println();
        System.out.println("========================================");
        System.out.println("ОТВЕТ для интеграла (а):");
        System.out.println("integral[0.8; 1.8] dx / sqrt(3*x^2 + 1) = " + result);
        System.out.println("========================================");
    }
}